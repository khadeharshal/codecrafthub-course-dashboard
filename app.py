from datetime import date, datetime, timezone
import json
import os
from pathlib import Path
from tempfile import NamedTemporaryFile

from flask import Flask, jsonify, request


# Create the Flask application instance.
app = Flask(__name__)


# Store courses.json in the same directory as this app.py file.
DATA_FILE = Path(__file__).resolve().parent / "courses.json"


# These are the only status values accepted by the API.
VALID_STATUSES = {
    "Not Started",
    "In Progress",
    "Completed",
}


class StorageError(Exception):
    """Raised when there is a problem reading or writing courses.json."""


def initialize_data_file():
    """
    Create courses.json with an empty list if it does not exist.
    """
    if DATA_FILE.exists():
        return

    try:
        DATA_FILE.parent.mkdir(parents=True, exist_ok=True)
        DATA_FILE.write_text("[]\n", encoding="utf-8")
    except OSError as error:
        raise StorageError(
            f"Unable to create data file: {DATA_FILE}"
        ) from error


def load_courses():
    """
    Read and return all courses from courses.json.

    Automatically creates courses.json if it does not already exist.
    Raises StorageError if the file cannot be read, contains invalid JSON,
    or does not contain a JSON list.
    """
    if not DATA_FILE.exists():
        initialize_data_file()
        return []

    try:
        with DATA_FILE.open("r", encoding="utf-8") as file:
            courses = json.load(file)
    except FileNotFoundError:
        initialize_data_file()
        return []
    except PermissionError as error:
        raise StorageError(
            "Permission denied while reading courses.json."
        ) from error
    except json.JSONDecodeError as error:
        raise StorageError(
            "The courses.json file contains invalid JSON."
        ) from error
    except OSError as error:
        raise StorageError(
            "Unable to read courses.json."
        ) from error

    if not isinstance(courses, list):
        raise StorageError(
            "The courses.json file must contain a JSON list."
        )

    return courses


def save_courses(courses):
    """
    Save all courses to courses.json safely.

    A temporary file is written and flushed first before atomically replacing
    the existing file. This ensures data is not corrupted if a write fails.
    """
    temporary_path = None

    try:
        DATA_FILE.parent.mkdir(parents=True, exist_ok=True)

        with NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=DATA_FILE.parent,
            prefix="courses_",
            suffix=".tmp",
            delete=False,
        ) as temporary_file:
            json.dump(courses, temporary_file, indent=2)
            temporary_file.write("\n")
            temporary_file.flush()
            os.fsync(temporary_file.fileno())
            temporary_path = Path(temporary_file.name)

        # Atomically replace the destination file once writing completes.
        os.replace(temporary_path, DATA_FILE)

    except (OSError, TypeError, ValueError) as error:
        # Clean up temporary file if write or replace fails.
        if temporary_path is not None:
            try:
                temporary_path.unlink(missing_ok=True)
            except OSError:
                pass

        raise StorageError(
            "Unable to save courses to courses.json."
        ) from error


def get_json_body():
    """
    Read and validate the incoming JSON request body.

    Returns:
        dict: The parsed JSON object.

    Raises:
        ValueError: If the body is missing, invalid, or not a JSON object.
    """
    if not request.data:
        raise ValueError("A JSON request body is required.")

    if not request.is_json:
        raise ValueError(
            "The request body must use the application/json content type."
        )

    try:
        body = request.get_json()
    except Exception as error:
        raise ValueError("The request body contains invalid JSON.") from error

    if not isinstance(body, dict):
        raise ValueError("The JSON request body must be an object.")

    return body


def validate_course_data(data):
    """
    Validate the fields required to create or replace a course.

    Returns:
        None if validation succeeds.
        str containing the error message if validation fails.
    """
    required_fields = {
        "name",
        "description",
        "target_date",
        "status",
    }

    missing_fields = required_fields - set(data.keys())
    if missing_fields:
        missing = ", ".join(sorted(missing_fields))
        return f"Missing required field(s): {missing}."

    # Disallow unexpected fields (id and created_at are generated by server).
    unknown_fields = set(data.keys()) - required_fields
    if unknown_fields:
        unknown = ", ".join(sorted(unknown_fields))
        return f"Unknown field(s): {unknown}."

    # Validate name: required non-empty string.
    if not isinstance(data["name"], str):
        return "The name field must be a string."
    if not data["name"].strip():
        return "The name field must be a non-empty string."

    # Validate description: required string.
    if not isinstance(data["description"], str):
        return "The description field must be a string."

    # Validate target_date: required valid date in YYYY-MM-DD format.
    if not isinstance(data["target_date"], str):
        return "The target_date field must be a string in YYYY-MM-DD format."

    try:
        parsed_date = date.fromisoformat(data["target_date"])
    except ValueError:
        return "The target_date field must be a valid date in YYYY-MM-DD format."

    if parsed_date.isoformat() != data["target_date"]:
        return "The target_date field must use YYYY-MM-DD format."

    # Validate status: must be one of the allowed statuses.
    if not isinstance(data["status"], str) or data["status"] not in VALID_STATUSES:
        return (
            'The status field must be one of "Not Started", '
            '"In Progress", or "Completed".'
        )

    return None


def find_course(courses, course_id):
    """
    Find a course by its integer ID.

    Returns:
        tuple: (course, index), or (None, None) if not found.
    """
    for index, course in enumerate(courses):
        if course.get("id") == course_id:
            return course, index

    return None, None


def get_next_course_id(courses):
    """
    Generate the next integer course ID starting at 1.

    Finds the largest existing ID and increments by 1 to prevent ID reuse.
    """
    if not courses:
        return 1

    existing_ids = [
        course["id"]
        for course in courses
        if isinstance(course.get("id"), int)
        and not isinstance(course.get("id"), bool)
    ]

    if not existing_ids:
        return 1

    return max(existing_ids) + 1


def current_timestamp():
    """
    Return current UTC time in ISO 8601 format.
    """
    return datetime.now(timezone.utc).isoformat()


def error_response(message, status_code):
    """
    Return a standardized JSON error response.
    """
    return jsonify({"error": message}), status_code


@app.before_request
def handle_preflight():
    """
    Handle CORS preflight OPTIONS requests from browser clients.
    """
    if request.method == "OPTIONS":
        response = app.make_default_options_response()
        response.headers["Access-Control-Allow-Origin"] = "*"
        response.headers["Access-Control-Allow-Methods"] = "GET, POST, PUT, DELETE, OPTIONS"
        response.headers["Access-Control-Allow-Headers"] = "Content-Type"
        return response


@app.after_request
def add_cors_headers(response):
    """
    Attach CORS headers to all responses to support Live Server and web clients.
    """
    response.headers["Access-Control-Allow-Origin"] = "*"
    response.headers["Access-Control-Allow-Methods"] = "GET, POST, PUT, DELETE, OPTIONS"
    response.headers["Access-Control-Allow-Headers"] = "Content-Type"
    return response


@app.errorhandler(StorageError)
def handle_storage_error(error):
    """
    Handle storage failures and return an HTTP 500 response.
    """
    return error_response(str(error), 500)


@app.get("/")
def index():
    """
    Root endpoint providing basic API information.
    """
    return jsonify({
        "name": "CodeCraftHub API",
        "status": "online",
        "endpoints": {
            "get_all_courses": "GET /api/courses",
            "get_one_course": "GET /api/courses/<id>",
            "create_course": "POST /api/courses",
            "update_course": "PUT /api/courses/<id>",
            "delete_course": "DELETE /api/courses/<id>"
        }
    }), 200


@app.post("/api/courses")
def create_course():
    """
    Add a new course.
    """
    try:
        data = get_json_body()
    except ValueError as error:
        return error_response(str(error), 400)

    validation_error = validate_course_data(data)
    if validation_error:
        return error_response(validation_error, 400)

    courses = load_courses()

    new_course = {
        "id": get_next_course_id(courses),
        "name": data["name"].strip(),
        "description": data["description"],
        "target_date": data["target_date"],
        "status": data["status"],
        "created_at": current_timestamp(),
    }

    courses.append(new_course)

    # Save to disk; raises StorageError if failed so success is not reported falsely.
    save_courses(courses)

    return jsonify(new_course), 201


@app.get("/api/courses")
def get_courses():
    """
    Retrieve all courses.
    """
    courses = load_courses()
    return jsonify(courses), 200


@app.get("/api/courses/<int:course_id>")
def get_course(course_id):
    """
    Retrieve one course by its integer ID.
    """
    courses = load_courses()
    course, _ = find_course(courses, course_id)

    if course is None:
        return error_response(
            f"Course with ID {course_id} was not found.",
            404,
        )

    return jsonify(course), 200


@app.put("/api/courses/<int:course_id>")
def update_course(course_id):
    """
    Update an existing course while preserving its id and created_at values.
    """
    try:
        data = get_json_body()
    except ValueError as error:
        return error_response(str(error), 400)

    validation_error = validate_course_data(data)
    if validation_error:
        return error_response(validation_error, 400)

    courses = load_courses()
    existing_course, course_index = find_course(courses, course_id)

    if existing_course is None:
        return error_response(
            f"Course with ID {course_id} was not found.",
            404,
        )

    updated_course = {
        # Preserve original server-managed values.
        "id": existing_course["id"],
        "created_at": existing_course["created_at"],

        # Update client-supplied values.
        "name": data["name"].strip(),
        "description": data["description"],
        "target_date": data["target_date"],
        "status": data["status"],
    }

    courses[course_index] = updated_course

    # Save changes and confirm write success before responding.
    save_courses(courses)

    return jsonify(updated_course), 200


@app.delete("/api/courses/<int:course_id>")
def delete_course(course_id):
    """
    Delete a course by its integer ID.
    """
    courses = load_courses()
    course, course_index = find_course(courses, course_id)

    if course is None:
        return error_response(
            f"Course with ID {course_id} was not found.",
            404,
        )

    courses.pop(course_index)

    # Save changes and confirm write success before responding.
    save_courses(courses)

    return "", 204


if __name__ == "__main__":
    # Ensure courses.json is initialized before starting the server.
    initialize_data_file()

    # Run the development server.
    app.run(debug=True)

